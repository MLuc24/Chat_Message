// Helper function to get all emojis from a category
export function getEmojisByCategory(categoryId: string): string[] {
  const category = EMOJI_CATEGORIES.find((cat) => cat.id === categoryId);
  return category?.emojis || [];
}

// Helper function to search emojis
export function searchEmojis(query: string): string[] {
  if (!query.trim()) return [];
  
  const lowerQuery = query.toLowerCase();
  const results: string[] = [];
  
  EMOJI_CATEGORIES.forEach((category) => {
    if (category.name.toLowerCase().includes(lowerQuery)) {
      results.push(...category.emojis.slice(0, 20)); // Limit results per category
    }
  });
  
  return results.slice(0, 100); // Max 100 results
}

// Get frequently used emojis (can be stored in localStorage)
export function getFrequentEmojis(): string[] {
  const stored = localStorage.getItem('frequentEmojis');
  if (stored) {
    try {
      return JSON.parse(stored);
    } catch {
      return [];
    }
  }
  
  // Default frequent emojis
  return ['😀', '😂', '❤️', '👍', '😊', '🙏', '😘', '💕', '😍', '🎉', '🔥', '👏', '✨', '💯', '🥰'];
}

// Save emoji as frequently used
export function addFrequentEmoji(emoji: string): void {
  const frequent = getFrequentEmojis();
  const filtered = frequent.filter((e) => e !== emoji);
  const updated = [emoji, ...filtered].slice(0, 30); // Keep top 30
  localStorage.setItem('frequentEmojis', JSON.stringify(updated));
}
